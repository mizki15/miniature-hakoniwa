/** ID の名前（B05a なら「掘る（ブロック）：土・草」） */
export function sfxName(id: string): string {
  if (SFX_NAMES[id]) return SFX_NAMES[id];
  const m = /^([A-F]\d\d)([a-z])$/.exec(id);
  if (m && SFX_NAMES[m[1]]) return `${SFX_NAMES[m[1]]}：${SUFFIX[m[1]]?.[m[2]] ?? m[2]}`;
  return id;
}
